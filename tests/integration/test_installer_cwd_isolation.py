def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _plant_tree(root: Path, marker: Path) -> Path:
    """Make ROOT an Apothem-shaped tree whose locator and engine mark MARKER."""
    _write(root / "pyproject.toml", '[project]\nname = "planted"\n')
    _write(
        root / "src" / "apothem" / "hooks" / "lib" / "find-python.sh",
        _LOCATOR.format(marker=marker),
    )
    _write(root / "src" / "apothem" / "__init__.py", "")
    _write(
        root / "src" / "apothem" / "__main__.py",
        _MARKER_MODULE.format(marker=str(marker)),
    )
    return root


def _plant_modules(folder: Path, marker: Path) -> Path:
    """Put modules in FOLDER that mark MARKER when imported: the site hooks
    (sitecustomize, usercustomize), json, click, rich, apothem and pip.

    sitecustomize.py runs only when the folder is on sys.path while Python
    starts, so it catches an empty or relative PYTHONPATH entry that a ``-c``
    program's own sys.path fix comes too late for.
    """
    module = _MARKER_MODULE.format(marker=str(marker))
    for name in ("sitecustomize.py", "usercustomize.py", "json.py", "click.py"):
        _write(folder / name, module)
    for package in ("rich", "apothem", "pip"):
        _write(folder / package / "__init__.py", module)
        _write(folder / package / "__main__.py", module)
    return folder


def _fake_checkout(root: Path, *, locator_marker: Path | None = None) -> Path:
    """A checkout with install.sh in place and a stand-in engine."""
    _write(root / "pyproject.toml", '[project]\nname = "fake-checkout"\n')
    installer = root / "scripts" / "installer" / "install.sh"
    installer.parent.mkdir(parents=True)
    shutil.copy2(INSTALLER, installer)
    _write(root / "src" / "apothem" / "__init__.py", "")
    _write(root / "src" / "apothem" / "__main__.py", _FAKE_ENGINE)
    _write(
        root / "src" / "apothem" / "schemas" / "profile.example.yaml",
        "identity: {}\n",
    )
    if locator_marker is not None:
        # A locator that marks it was used, then finds the test's interpreter.
        _write(
            root / "src" / "apothem" / "hooks" / "lib" / "find-python.sh",
            f"find_real_python() {{ touch '{locator_marker}'; command -v python3; }}\n",
        )
    return root


def _env(
    tmp_path: Path, *, pythonpath: str | None = None, **extra: str
) -> dict[str, str]:
    """An environment with an isolated HOME, no pip index, a python3 that is
    the test's interpreter, and PYTHONPATH set to PYTHONPATH when given."""
    home = tmp_path / "home"
    home.mkdir(exist_ok=True)
    (tmp_path / "temp").mkdir(exist_ok=True)
    shim_dir = tmp_path / "python-shim"
    shim_dir.mkdir(exist_ok=True)
    write_python_shim(shim_dir / "python3")
    env = {k: v for k, v in hermetic_git_env().items() if not k.startswith("APOTHEM_")}
    for key in [k for k in env if k.startswith(("PIP_", "PYTHON"))]:
        del env[key]
    env.pop("XDG_CONFIG_HOME", None)
    env.update(
        {
            "HOME": str(home),
            "TMPDIR": str(tmp_path / "temp"),
            "PIP_NO_INDEX": "1",
            "PIP_CONFIG_FILE": os.devnull,
            "PATH": f"{shim_dir}{os.pathsep}{env.get('PATH', os.defpath)}",
            "APOTHEM_HOME": str(tmp_path / "apothem-home"),
            "APOTHEM_BIN_DIR": str(tmp_path / "bin"),
            "FAKE_ENGINE_RECORD": str(tmp_path / "engine-record.jsonl"),
        }
    )
    if pythonpath is not None:
        env["PYTHONPATH"] = pythonpath
    env.update(extra)
    return env


def _engine_calls(tmp_path: Path) -> list[dict[str, object]]:
    record = tmp_path / "engine-record.jsonl"
    if not record.exists():
        return []
    return [
        json.loads(line) for line in record.read_text(encoding="utf-8").splitlines()
    ]


def _run(
    args: list[str],
    *,
    cwd: Path,
    env: dict[str, str],
    stdin_file: Path | None = None,
) -> subprocess.CompletedProcess[str]:
    if stdin_file is None:
        return subprocess.run(
            args,
            cwd=str(cwd),
            env=env,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            timeout=RUN_TIMEOUT_SECONDS,
            check=False,
        )
    with stdin_file.open("rb") as script:
        return subprocess.run(
            args,
            cwd=str(cwd),
            env=env,
            stdin=script,
            capture_output=True,
            text=True,
            timeout=RUN_TIMEOUT_SECONDS,
            check=False,
        )



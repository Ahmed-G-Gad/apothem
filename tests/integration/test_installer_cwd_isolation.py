def test_the_shim_keeps_absolute_pythonpath_entries_after_the_engine(
    tmp_path: Path,
) -> None:
    """An absolute entry of the user's PYTHONPATH still reaches the engine,
    after the engine's own paths."""
    checkout = _fake_checkout(tmp_path / "checkout")
    install = _run(
        ["sh", str(INSTALLER)],
        cwd=tmp_path,
        env=_env(tmp_path, APOTHEM_SOURCE=str(checkout)),
    )
    assert install.returncode == 0, install.stdout + install.stderr
    extra = tmp_path / "user-site"
    _write(extra / "apothem_user_probe.py", "")
    probe = tmp_path / "probe"
    probe.mkdir()
    shim = (tmp_path / "bin" / "apothem").read_text(encoding="utf-8")
    # Make the shim print sys.path and stop before it starts the engine.
    (probe / "apothem").write_text(
        shim.replace(
            "import runpy;",
            "print(chr(10).join(sys.path)); raise SystemExit(0);",
        ),
        encoding="utf-8",
        newline="\n",
    )
    (probe / "apothem").chmod(0o755)

    result = _run(
        [str(probe / "apothem")],
        cwd=tmp_path,
        env=_env(tmp_path, pythonpath=f":{extra}:relative:"),
    )

    assert result.returncode == 0, result.stderr
    path = result.stdout.splitlines()
    engine_src = str(checkout.resolve() / "src")
    assert engine_src in path, (engine_src, path)
    assert str(extra) in path, (extra, path)
    assert path.index(engine_src) < path.index(str(extra)), path
    assert "" not in path, path
    assert not any(entry.endswith("/relative") for entry in path), path
    assert str(tmp_path) not in path, path


def test_the_pip_start_ignores_a_pip_package_in_the_current_folder(
    tmp_path: Path,
) -> None:
    """The dependency auto-install starts pip from the interpreter's own
    site-packages, never a pip/ package in the current folder.

    click is made unimportable by a python3 wrapper that puts a folder whose
    click.py raises ImportError first on PYTHONPATH, so --yes reaches pip,
    which has no index and fails; the planted pip must not run."""
    marker = tmp_path / "shadow-ran"
    workdir = _plant_modules(tmp_path / "workdir", marker)
    checkout = _fake_checkout(tmp_path / "checkout")
    blocker = tmp_path / "no-click"
    _write(blocker / "click.py", "raise ImportError('click hidden by the test')\n")
    env = _env(tmp_path, APOTHEM_SOURCE=str(checkout))
    wrapper_dir = tmp_path / "python-wrapper"
    wrapper_dir.mkdir()
    real = Path(sys.executable).as_posix()
    (wrapper_dir / "python3").write_text(
        "#!/bin/sh\n"
        f'PYTHONPATH="{blocker}${{PYTHONPATH:+:${{PYTHONPATH}}}}" exec "{real}" "$@"\n',
        encoding="utf-8",
        newline="\n",
    )
    (wrapper_dir / "python3").chmod(0o755)
    env["PATH"] = f"{wrapper_dir}{os.pathsep}{env['PATH']}"

    result = _run(["sh", str(INSTALLER), "--yes"], cwd=workdir, env=env)

    combined = result.stdout + result.stderr
    assert "Missing Python prerequisites" in combined, combined
    assert "Installing click==" in combined or "pip is unavailable" in combined, (
        combined
    )
    assert not marker.exists(), combined

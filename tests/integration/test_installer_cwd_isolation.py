"""The POSIX installers never take code from the folder they run in.

Two classes of fault are covered, each on ``scripts/installer/install.sh``
and, where it applies, ``scripts/installer/update.sh``:

- **A local tree from the current folder.** The documented one-liner pipes
  install.sh into ``sh``, so ``$0`` is the shell's name, not the script. The
  installer used to fall back to the current folder then: it sourced
  ``<cwd>/../../src/apothem/hooks/lib/find-python.sh`` and walked parent
  folders for an Apothem-shaped tree, which it installed and ran unverified.
  A local tree is now used only when ``APOTHEM_SOURCE`` names it or when the
  script runs by path from its own checkout.
- **Modules from the current folder.** ``python -c`` puts ``''`` first on
  ``sys.path`` and ``python -m`` puts the working directory there, so a
  ``click.py`` or an ``apothem/`` package in the current folder ran instead of
  the real one in the dependency probe, the engine runs, the installed
  ``apothem`` shim, update.sh, uninstall.sh and the pip start of the
  dependency auto-install. Each start now sets ``PYTHONSAFEPATH=1`` and drops
  a leading ``''`` itself, and keeps only the absolute entries of the user's
  ``PYTHONPATH``: an empty or relative entry is the current folder too.
- **A git repository around the current folder.** ``git ls-remote`` and
  ``git clone`` read the config of a repository they run inside, and that
  config can make git run a program. They now run from an empty folder.

Every planted file writes a marker when it runs; each test asserts that no
marker appears. A fake checkout carries a stand-in engine
(``src/apothem/__main__.py``) that records the arguments and the working
directory it was started with, so the tests also show that the engine sees
the user's arguments and folder unchanged.

The fetched path uses the fixtures of ``test_installer_release_mode.py``: a
``file://`` release, a stub cosign and a stub gpg, in a dry run. The scripts
run on the interpreter running these tests (``tests._shared.python_shim``),
which must import click and rich.
"""


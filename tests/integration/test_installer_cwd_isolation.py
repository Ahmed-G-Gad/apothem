@pytest.mark.parametrize("pythonpath", USER_PYTHONPATHS)
def test_install_probe_engine_and_shim_ignore_modules_in_the_current_folder(
    tmp_path: Path, pythonpath: str | None
) -> None:
    """The dependency probe, the engine's install and verify runs, and the
    installed shim all run with the planted modules in the current folder,
    and none of them runs, whatever the user's PYTHONPATH; the engine sees the
    user's arguments and folder."""
    marker = tmp_path / "shadow-ran"
    workdir = _plant_modules(tmp_path / "workdir", marker)
    checkout = _fake_checkout(tmp_path / "checkout")
    env = _env(tmp_path, pythonpath=pythonpath, APOTHEM_SOURCE=str(checkout))

    result = _run(["sh", str(INSTALLER)], cwd=workdir, env=env)

    combined = result.stdout + result.stderr
    assert result.returncode == 0, combined
    assert not marker.exists(), combined
    calls = _engine_calls(tmp_path)
    assert [call["argv"][:1] for call in calls] == [["install"], ["verify"]], calls
    assert all(call["cwd"] == str(workdir.resolve()) for call in calls), calls

    shim = tmp_path / "bin" / "apothem"
    assert shim.is_file(), combined
    shim_result = _run([str(shim), "doctor", "--json", "a b", ""], cwd=workdir, env=env)

    assert shim_result.returncode == 0, shim_result.stderr
    assert not marker.exists(), shim_result.stdout + shim_result.stderr
    last = _engine_calls(tmp_path)[-1]
    assert last == {
        "argv": ["doctor", "--json", "a b", ""],
        "cwd": str(workdir.resolve()),
    }



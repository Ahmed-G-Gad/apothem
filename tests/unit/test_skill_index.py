"""Unit tests for the generated session-start skill index.

The index is built from the catalog frontmatter and a curated cue map, shipped
as ``hooks/messages/skill-index.md``, and held to the generator by a drift test.
These tests pin its content, its size cap, its determinism, and the drift gate.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pytest

from apothem.lib import skill_index as si

_REPO_ROOT = Path(__file__).resolve().parents[2]
_SRC_ROOT = _REPO_ROOT / "src" / "apothem"
_HOOKS_LIB = _SRC_ROOT / "hooks" / "lib"
_COMMITTED = _SRC_ROOT / si.INDEX_MESSAGE_REL


def _model_facing(text: str) -> str:
    """Return *text* as the hook emitters deliver it to the model."""
    if str(_HOOKS_LIB) not in sys.path:
        sys.path.insert(0, str(_HOOKS_LIB))
    from message_text import strip_maintainer_text

    return strip_maintainer_text(text)


def _group_lines(body: str) -> list[str]:
    """Return the per-domain lines of *body*, without the header paragraph."""
    return body.split("\n\n", 1)[1].splitlines()


def _write_member(root: Path, kind: str, name: str, frontmatter: str) -> None:
    if kind == "skill":
        path = root / "skills" / name / "SKILL.md"
    else:
        path = root / "commands" / f"{name}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"---\nname: {name}\n{frontmatter}---\n\nBody.\n", encoding="utf-8")


def test_committed_index_matches_the_generator() -> None:
    """The committed message is exactly what the generator renders now."""
    assert _COMMITTED.read_text(encoding="utf-8") == si.build_index_message(_SRC_ROOT)


def test_index_is_deterministic() -> None:
    assert si.build_index_message(_SRC_ROOT) == si.build_index_message(_SRC_ROOT)


def test_model_facing_text_is_within_the_cap() -> None:
    body = _model_facing(si.build_index_message(_SRC_ROOT))
    assert len(body) <= si.INDEX_MAX_CHARS
    # The cap guards the cost; a near-empty index would also pass it, so floor it.
    assert len(body) > 800


def test_index_text_has_no_maintainer_text_after_stripping() -> None:
    body = _model_facing(si.build_index_message(_SRC_ROOT))
    assert "SPDX" not in body
    assert "Bindings" not in body
    assert "Generated by" not in body


def _shipped_listable_skills() -> dict[str, bool]:
    """Return name -> manual for every listable skill, read independently.

    The oracle is the frontmatter itself, parsed here without the generator: a
    skill folder wins over a same-named command, a member that is not
    user-invocable is not listed, and ``disable-model-invocation: true`` marks a
    manual one.
    """

    def flags(text: str) -> tuple[bool, bool]:
        head = text.split("\n---\n", 1)[0]
        hidden = re.search(r"^(?:userInvocable|user-invocable):\s*false", head, re.M)
        manual = re.search(r"^disable-model-invocation:\s*true", head, re.M)
        return hidden is not None, manual is not None

    found: dict[str, bool] = {}
    hidden_names: set[str] = set()
    for skill_md in sorted((_SRC_ROOT / "skills").glob("*/SKILL.md")):
        hidden, manual = flags(skill_md.read_text(encoding="utf-8"))
        if hidden:
            hidden_names.add(skill_md.parent.name)
        else:
            found[skill_md.parent.name] = manual
    for command_md in sorted((_SRC_ROOT / "commands").glob("*.md")):
        name = command_md.stem
        if name == "README" or name in found or name in hidden_names:
            continue
        found[name] = flags(command_md.read_text(encoding="utf-8"))[1]
    return found


def test_every_listed_name_is_a_shipped_skill() -> None:
    """Names, braces expanded, are real catalog members, and none is missing."""
    oracle = _shipped_listable_skills()
    shipped = set(oracle)
    assert shipped == {entry.name for entry in si.collect_entries(_SRC_ROOT)}
    body = _model_facing(si.build_index_message(_SRC_ROOT))
    listed: set[str] = set()
    manual_listed: set[str] = set()
    for line in _group_lines(body):
        # Cues in parentheses are prose; a cue word that equals a skill name
        # must not stand in for that skill.
        items = re.sub(r"\([^)]*\)", "", line.split("): ", 1)[1])
        manual_listed.update(re.findall(r"/apothem:([a-z0-9-]+)", items))
        for token in re.findall(
            r"(?:/apothem:)?[a-z0-9]+(?:-[a-z0-9-]+)?(?:-\{[^}]*\})?", items
        ):
            token = token.removeprefix("/apothem:")
            if "-{" in token:
                family, tails = token.rstrip("}").split("-{")
                listed.update(f"{family}-{tail}" for tail in tails.split(","))
            else:
                listed.add(token)
    assert listed == shipped
    assert manual_listed == {name for name, manual in oracle.items() if manual}


def test_reference_templates_are_not_listed() -> None:
    names = {entry.name for entry in si.collect_entries(_SRC_ROOT)}
    assert "plan-suite" not in names
    assert "research-suite" not in names
    assert "plan-suite" not in _model_facing(si.build_index_message(_SRC_ROOT))


def test_manual_skills_carry_the_plugin_prefix() -> None:
    entries = si.collect_entries(_SRC_ROOT)
    body = _model_facing(si.build_index_message(_SRC_ROOT))
    manual = [entry.name for entry in entries if entry.manual]
    assert manual, "the catalog ships manual skills"
    for name in manual:
        assert f"{si.MANUAL_PREFIX}{name}" in body
    for entry in entries:
        if not entry.manual:
            pattern = re.escape(f"{si.MANUAL_PREFIX}{entry.name}") + r"(?![\w-])"
            assert re.search(pattern, body) is None, entry.name


def test_groups_render_in_domain_order() -> None:
    body = _model_facing(si.build_index_message(_SRC_ROOT))
    labels = [line.split(" (", 1)[0] for line in _group_lines(body)]
    assert labels == [label for _key, label, _cue in si.DOMAINS]


def test_every_catalog_name_has_a_cue_entry_in_a_known_domain() -> None:
    domains = {key for key, _label, _cue in si.DOMAINS}
    for entry in si.collect_entries(_SRC_ROOT):
        assert entry.name in si.CATALOG_CUES, entry.name
        assert si.CATALOG_CUES[entry.name][0] in domains


def test_cue_map_has_no_stale_names() -> None:
    """A removed or renamed skill leaves no orphan cue behind."""
    shipped = {entry.name for entry in si.collect_entries(_SRC_ROOT)}
    reference_only = {"plan-suite", "research-suite"}
    assert set(si.CATALOG_CUES) <= shipped | reference_only
    assert not (set(si.CATALOG_CUES) & reference_only)


def test_unmapped_name_fails_generation(tmp_path: Path) -> None:
    _write_member(tmp_path, "skill", "brand-new-skill", "userInvocable: true\n")
    (tmp_path / "commands").mkdir(exist_ok=True)
    with pytest.raises(si.SkillIndexError, match="brand-new-skill"):
        si.build_index_message(tmp_path)


def test_oversize_index_fails_generation(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(si, "INDEX_MAX_CHARS", 200)
    with pytest.raises(si.SkillIndexError, match="cap"):
        si.build_index_message(_SRC_ROOT)


def test_collect_entries_reads_flags_and_merges_command_and_skill(
    tmp_path: Path,
) -> None:
    _write_member(tmp_path, "skill", "alpha", "disable-model-invocation: false\n")
    _write_member(tmp_path, "command", "alpha", "disable-model-invocation: true\n")
    _write_member(tmp_path, "command", "beta", "disable-model-invocation: true\n")
    _write_member(tmp_path, "skill", "gamma", "disable-model-invocation: false\n")
    _write_member(
        tmp_path,
        "skill",
        "tmpl",
        "userInvocable: false\ndisable-model-invocation: true\n",
    )
    (tmp_path / "commands" / "README.md").write_text("# index\n", encoding="utf-8")

    entries = {entry.name: entry.manual for entry in si.collect_entries(tmp_path)}

    # The skill's flag wins over a same-named command, as in the install.
    assert entries == {"alpha": False, "beta": True, "gamma": False}


def test_collect_entries_requires_both_catalog_directories(tmp_path: Path) -> None:
    (tmp_path / "skills").mkdir()
    with pytest.raises(si.SkillIndexError, match="commands"):
        si.collect_entries(tmp_path)


def test_family_collapse_needs_three_cueless_invocable_members() -> None:
    entries = [
        si.IndexEntry(name, False)
        for name in ("plan-spec", "plan-review", "plan-audit", "plan")
    ] + [si.IndexEntry("plan-execute", True)]
    items = si._group_items(entries)
    assert "plan-{audit,review,spec}" in items
    assert "plan (full pipeline)" in items
    assert "/apothem:plan-execute (one phase)" in items

    two = si._group_items(
        [si.IndexEntry("plan-spec", False), si.IndexEntry("plan-review", False)]
    )
    assert two == ["plan-review", "plan-spec"]


def test_standalone_name_equal_to_a_family_prefix_is_kept(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    # With no cue, 'plan' is plain; it must still render beside the collapsed
    # plan-{...} family instead of being folded into it.
    cues = dict(si.CATALOG_CUES)
    cues["plan"] = ("planning", "")
    monkeypatch.setattr(si, "CATALOG_CUES", cues)
    entries = [
        si.IndexEntry(name, False)
        for name in ("plan", "plan-spec", "plan-review", "plan-audit")
    ]
    assert si._group_items(entries) == ["plan", "plan-{audit,review,spec}"]

RAISED_FLOOR_LOCKS = [
    lock.filename
    for lock in refresh_ci_locks.LOCKS
    if lock.python_floor != refresh_ci_locks.PYTHON_FLOOR
]


def test_the_pip_audit_and_pre_commit_locks_raise_the_floor() -> None:
    # pre-commit needs Python 3.11. The pip-audit lock is compiled for 3.11 so that
    # no line of it pins filelock 4.1.0, whose advisories only a 3.11 release fixes.
    assert RAISED_FLOOR_LOCKS == [
        "requirements-ci-pip-audit.txt",
        "requirements-ci-pre-commit.txt",
    ]


@pytest.mark.parametrize("filename", RAISED_FLOOR_LOCKS)
def test_a_lock_with_a_raised_floor_is_never_installed_below_it(filename: str) -> None:
    lock = refresh_ci_locks.lock_by_filename(filename)
    floor = _major_minor(lock.python_floor)
    labels = [label for label, _env in environments(lock.python_floor)]
    assert labels
    for label in labels:
        assert _major_minor(label.removeprefix("py").split("-")[0]) >= floor, label
    # A line marked for a Python below the floor would be dead weight: the floor
    # drops it, and a scanner that ignores markers would still report it.
    below = f"< '{lock.python_floor}'"
    assert not any(
        f"python_full_version {below}" in pin.line
        or f"python_version {below}" in pin.line
        for pin in load_pins(filename)
    )



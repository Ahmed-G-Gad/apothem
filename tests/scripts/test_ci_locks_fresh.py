"""The hash-locked CI requirement files still satisfy their inputs.

CI installs its Python dependencies from ``scripts/ci/requirements-ci-*.txt``
(``python -m pip install --require-hashes -r <lock>``). A lock is generated by
``scripts/dev/refresh_ci_locks.py`` from the table in
``scripts/dev/ci_lock_table.py``. When ``pyproject.toml`` raises a floor or
changes a pin, or the table changes a tool version, and the locks are not
regenerated, CI keeps installing the old version and the change is not tested.
This module catches that without uv or network access: it reads the committed
locks, evaluates their environment markers for Python 3.10 to 3.15 on Linux,
Windows and macOS, and checks that the version each lock pins satisfies every
requirement of its inputs. It also holds every lock to the shape the workflows
rely on: a hash on every line, a header that records the lock date, the
cooldown, the cutoff and the cooldown exceptions of its table row, one lock date
and one cutoff across the folder, and no pip pin outside
``requirements-ci-pip.txt``.

``packaging`` is not a project dependency; it is present wherever this test runs
because pytest requires it.
"""


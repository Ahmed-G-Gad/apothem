"""The hash-locked CI requirement files still satisfy ``pyproject.toml``.

CI installs its Python dependencies from ``scripts/ci/requirements-ci-*.txt``
(``python -m pip install --require-hashes -r <lock>``). A lock is generated by
``scripts/dev/refresh_ci_locks.py``; when ``pyproject.toml`` raises a floor or
changes a pin and the lock is not regenerated, CI keeps installing the old
version and the change is not tested. This module catches that without uv or
network access: it reads the committed locks, evaluates their environment
markers for Python 3.10 to 3.15 on Linux, Windows and macOS, and checks that
the version each lock pins satisfies every requirement of the package.

``packaging`` is not a project dependency; it is present wherever this test runs
because pytest requires it.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest
from packaging.markers import Marker, default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

if sys.version_info >= (3, 11):
    import tomllib
else:  # Python 3.10: tomli is in the dev lock for python_full_version < 3.11.
    import tomli as tomllib

REPO_ROOT = Path(__file__).resolve().parents[2]
CI_DIR = REPO_ROOT / "scripts" / "ci"
sys.path.insert(0, str(REPO_ROOT / "scripts" / "dev"))
sys.path.insert(0, str(REPO_ROOT / "src"))

import refresh_ci_locks  # noqa: E402

REFRESH = "scripts/dev/refresh_ci_locks.py"
DEV, RUNTIME, TEST, PREREQS = (
    "requirements-ci-dev.txt",
    "requirements-ci-runtime.txt",
    "requirements-ci-test.txt",
    "requirements-ci-prereqs.txt",
)
_HASH_RE = re.compile(r"--hash=sha256:[0-9a-f]{64}")

# Full versions, so the `python_full_version < '3.10.2'` markers of importlib-metadata
# and zipp are exercised on both sides.
PYTHONS = (
    "3.10.0",
    "3.10.1",
    "3.10.2",
    "3.10.20",
    "3.11.0",
    "3.12.0",
    "3.13.0",
    "3.14.0",
    "3.15.0",
)
PLATFORMS = {
    "linux": {
        "sys_platform": "linux",
        "platform_system": "Linux",
        "os_name": "posix",
        "platform_machine": "x86_64",
    },
    "win32": {
        "sys_platform": "win32",
        "platform_system": "Windows",
        "os_name": "nt",
        "platform_machine": "AMD64",
    },
    "darwin": {
        "sys_platform": "darwin",
        "platform_system": "Darwin",
        "os_name": "posix",
        "platform_machine": "arm64",
    },
}


@dataclass(frozen=True)
class Pin:
    """One requirement line of a lock: name, version, marker and hash count."""

    name: str
    version: Version
    marker: Marker | None
    hashes: int
    line: str


def _logical_lines(text: str) -> list[str]:
    """Join ``\\`` continuations; drop comments and blank lines."""
    lines: list[str] = []
    pending: list[str] = []
    for raw in text.splitlines():
        stripped = raw.strip()
        if not pending and (not stripped or stripped.startswith("#")):
            continue
        if stripped.endswith("\\"):
            pending.append(stripped[:-1].strip())
            continue
        pending.append(stripped)
        lines.append(" ".join(part for part in pending if part))
        pending = []
    assert not pending, "a requirement line ends with a backslash"
    return lines


def _read_text(filename: str) -> str:
    return (CI_DIR / filename).read_bytes().decode("utf-8")


def load_pins(filename: str) -> list[Pin]:
    """Parse the committed lock ``filename`` into pins."""
    pins: list[Pin] = []
    for line in _logical_lines(_read_text(filename)):
        requirement_text = line.split("--hash=", 1)[0].strip()
        requirement = Requirement(requirement_text)
        specifiers = list(requirement.specifier)
        assert len(specifiers) == 1, line
        assert specifiers[0].operator == "==", line
        pins.append(
            Pin(
                name=canonicalize_name(requirement.name),
                version=Version(specifiers[0].version),
                marker=requirement.marker,
                hashes=len(_HASH_RE.findall(line)),
                line=line,
            )
        )
    return pins


def environments() -> list[tuple[str, dict[str, str]]]:
    """Return ``(label, marker environment)`` for every supported combination."""
    result: list[tuple[str, dict[str, str]]] = []
    for python in PYTHONS:
        major_minor = ".".join(python.split(".")[:2])
        for platform, overrides in PLATFORMS.items():
            env = dict(default_environment())
            env.update(
                {
                    "python_full_version": python,
                    "python_version": major_minor,
                    "implementation_name": "cpython",
                    "platform_python_implementation": "CPython",
                    "implementation_version": python,
                    **overrides,
                }
            )
            result.append((f"py{python}-{platform}", env))
    return result


def resolve(pins: list[Pin], env: dict[str, str]) -> dict[str, Version]:
    """Return the version per package that a lock installs in ``env``."""
    installed: dict[str, Version] = {}
    for pin in pins:
        if pin.marker is not None and not pin.marker.evaluate(env):
            continue
        assert pin.name not in installed, (
            f"{pin.name} is pinned twice for the same environment: "
            f"{installed[pin.name]} and {pin.version}"
        )
        installed[pin.name] = pin.version
    return installed


def _pyproject() -> dict[str, object]:
    return tomllib.loads((REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"))


def project_requirements(extra: str | None = None) -> list[Requirement]:
    """Return ``[project.dependencies]``, plus one extra when ``extra`` is given."""
    project = _pyproject()["project"]
    assert isinstance(project, dict)
    texts = list(project["dependencies"])
    if extra is not None:
        texts += project["optional-dependencies"][extra]
    return [Requirement(text) for text in texts]


def _stale(filename: str, problems: list[str]) -> str:
    detail = "\n  - ".join(sorted(set(problems)))
    return (
        f"scripts/ci/{filename} no longer satisfies pyproject.toml:\n  - {detail}\n"
        f"Run `python {REFRESH}` (needs uv) to regenerate every CI lock, then "
        "commit the changed files."
    )


def assert_satisfies(filename: str, requirements: list[Requirement]) -> None:
    """Fail unless the lock ``filename`` meets every requirement in every environment."""
    pins = load_pins(filename)
    problems: list[str] = []
    for label, env in environments():
        installed = resolve(pins, env)
        for requirement in requirements:
            if requirement.marker is not None and not requirement.marker.evaluate(env):
                continue
            name = canonicalize_name(requirement.name)
            version = installed.get(name)
            if version is None:
                problems.append(f"{requirement} is not pinned ({label})")
            elif not requirement.specifier.contains(version, prereleases=True):
                problems.append(f"{requirement} but the lock pins {version} ({label})")
    assert not problems, _stale(filename, problems)


# --- the locks hold to pyproject.toml ----------------------------------------


def test_dev_lock_satisfies_runtime_and_dev_requirements() -> None:
    assert_satisfies(DEV, project_requirements("dev"))


def test_runtime_lock_satisfies_runtime_requirements() -> None:
    assert_satisfies(RUNTIME, project_requirements())


def test_test_lock_satisfies_runtime_requirements_and_the_test_tools() -> None:
    tools = [Requirement(text) for text in ("pytest", "pytest-xdist", "build")]
    assert_satisfies(TEST, [*project_requirements(), *tools])


def test_prereqs_lock_satisfies_the_host_prerequisites() -> None:
    from apothem.__main__ import HOST_PREREQUISITES

    assert_satisfies(
        PREREQS, [Requirement(spec) for _module, spec in HOST_PREREQUISITES]
    )


def test_prereqs_lock_holds_only_the_click_and_rich_closure() -> None:
    names = {pin.name for pin in load_pins(PREREQS)}
    assert {"click", "rich"} <= names
    assert names.isdisjoint({"pyyaml", "jsonschema", "pytest", "attrs", "referencing"})


def test_dev_and_test_locks_agree_on_the_shared_test_tools() -> None:
    for label, env in environments():
        dev = resolve(load_pins(DEV), env)
        test = resolve(load_pins(TEST), env)
        for name in ("pytest", "pytest-xdist"):
            assert dev[name] == test[name], (
                f"{name} is {dev[name]} in {DEV} and {test[name]} in {TEST} ({label}); "
                f"run `python {REFRESH}` so every lock is compiled together"
            )


def test_every_runtime_pin_matches_in_the_other_locks() -> None:
    for label, env in environments():
        runtime = resolve(load_pins(RUNTIME), env)
        for filename in (DEV, TEST):
            other = resolve(load_pins(filename), env)
            for name, version in runtime.items():
                assert other.get(name) == version, (
                    f"{name} is {version} in {RUNTIME} and {other.get(name)} in "
                    f"{filename} ({label}); run `python {REFRESH}`"
                )


# --- the shape of every lock ---------------------------------------------------


@pytest.mark.parametrize("filename", [DEV, RUNTIME, TEST, PREREQS])
def test_every_requirement_line_carries_a_hash(filename: str) -> None:
    pins = load_pins(filename)
    assert pins, filename
    missing = [pin.line for pin in pins if pin.hashes == 0]
    assert not missing, f"{filename} has a requirement without --hash=sha256: {missing}"


@pytest.mark.parametrize("filename", [DEV, RUNTIME, TEST, PREREQS])
def test_no_editable_url_or_option_lines(filename: str) -> None:
    for line in _logical_lines(_read_text(filename)):
        assert not line.startswith(("-", "git+", "http")), line
        assert " @ " not in line, line


@pytest.mark.parametrize("filename", [DEV, RUNTIME, TEST, PREREQS])
def test_lock_header_records_the_date_and_the_licence(filename: str) -> None:
    text = _read_text(filename)
    assert "\r" not in text
    assert text.startswith("# SPDX-License-" + "Identifier: MIT\n")
    timestamp, uv_version = refresh_ci_locks.parse_header(text)
    assert timestamp is not None, f"{filename} records no `Locked as of:` timestamp"
    assert uv_version is not None, f"{filename} records no uv version"


def test_locks_share_one_lock_date() -> None:
    stamps = {
        filename: refresh_ci_locks.parse_header(_read_text(filename))[0]
        for filename in (DEV, RUNTIME, TEST, PREREQS)
    }
    assert len(set(stamps.values())) == 1, (
        f"the locks were compiled on different dates: {stamps}; "
        f"run `python {REFRESH}` so they move together"
    )


def test_table_matches_the_files_on_disk() -> None:
    table = {lock.filename for lock in refresh_ci_locks.LOCKS}
    on_disk = {path.name for path in CI_DIR.glob("requirements-ci-*.txt")} - {
        "requirements-ci-pip.txt"
    }
    assert table == on_disk


# --- the test itself catches a stale lock --------------------------------------


def _mini_lock(version: str) -> list[Pin]:
    line = f"click=={version} --hash=sha256:{'a' * 64}"
    return [
        Pin(
            "click",
            Version(version),
            None,
            1,
            line,
        )
    ]


def test_resolve_honours_markers_for_python_and_platform() -> None:
    pins = [
        Pin("tomli", Version("2.5.0"), Marker("python_full_version < '3.11'"), 1, ""),
        Pin("colorama", Version("0.4.6"), Marker("sys_platform == 'win32'"), 1, ""),
    ]
    by_label = dict(environments())
    assert set(resolve(pins, by_label["py3.10.0-win32"])) == {"tomli", "colorama"}
    assert set(resolve(pins, by_label["py3.12.0-linux"])) == set()
    assert set(resolve(pins, by_label["py3.11.0-win32"])) == {"colorama"}


def test_a_package_pinned_twice_in_one_environment_is_reported() -> None:
    pins = [*_mini_lock("1.0"), *_mini_lock("2.0")]
    env = environments()[0][1]
    with pytest.raises(AssertionError, match="pinned twice"):
        resolve(pins, env)


def test_a_stale_lock_names_the_refresh_script(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setitem(globals(), "load_pins", lambda name: _mini_lock("8.4.1"))
    with pytest.raises(AssertionError, match=r"refresh_ci_locks\.py"):
        assert_satisfies(RUNTIME, [Requirement("click==8.4.2")])


def test_a_missing_package_is_reported(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setitem(globals(), "load_pins", lambda name: _mini_lock("8.4.2"))
    with pytest.raises(AssertionError, match=re.escape("rich>=15.0.0 is not pinned")):
        assert_satisfies(RUNTIME, [Requirement("rich>=15.0.0")])

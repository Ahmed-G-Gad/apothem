def assert_no_pip_pin(filename: str) -> None:
    """Fail when ``filename`` pins pip, which only the Dependabot lock may do."""
    names = {pin.name for pin in load_pins(filename)}
    assert "pip" not in names, (
        f"scripts/ci/{filename} pins pip; only scripts/ci/{PIP_LOCK} may, so "
        "Dependabot keeps the one pip pin current. Compile every lock with "
        f"--no-emit-package pip (`python {REFRESH}` does)."
    )


@pytest.mark.parametrize("filename", ALL_LOCKS)
def test_no_lock_but_the_pip_lock_pins_pip(filename: str) -> None:
    assert_no_pip_pin(filename)


def test_a_lock_that_pins_pip_is_caught(monkeypatch: pytest.MonkeyPatch) -> None:
    pip_pin = Pin("pip", Version("26.2.2"), None, 1, "pip==26.2.2")
    monkeypatch.setitem(globals(), "load_pins", lambda name: [pip_pin])
    with pytest.raises(AssertionError, match=r"--no-emit-package pip"):
        assert_no_pip_pin("requirements-ci-pip-audit.txt")



@pytest.mark.parametrize("filename", ALL_LOCKS)
def test_lock_header_records_the_dates_the_licence_and_the_uv_version(
    filename: str,
) -> None:
    text = _read_text(filename)
    assert "\r" not in text
    assert text.startswith("# SPDX-License-" + "Identifier: MIT\n")
    header = refresh_ci_locks.parse_header(text)
    assert header.missing() == [], f"{filename} lacks a header line: {header.missing()}"
    assert header.locked_as_of is not None
    assert header.cooldown_days is not None
    assert header.cutoff == refresh_ci_locks.cutoff_timestamp(
        header.locked_as_of, header.cooldown_days
    ), (
        f"{filename} records a cutoff that is not its lock date less its cooldown; "
        f"run `python {REFRESH}`"
    )


@pytest.mark.parametrize("filename", ALL_LOCKS)
def test_lock_header_names_its_install_command_and_its_python_floor(
    filename: str,
) -> None:
    lock = refresh_ci_locks.lock_by_filename(filename)
    text = _read_text(filename)
    assert f"#   python -m pip install --require-hashes -r {lock.relpath}\n" in text, (
        filename
    )
    header_text = " ".join(
        line.removeprefix("#").strip()
        for line in text.splitlines()
        if line.startswith("#")
    )
    assert f"One universal lock for Python {lock.python_floor} and later" in header_text


def _recorded_exception_lines(filename: str) -> list[str]:
    return [
        line
        for line in _read_text(filename).splitlines()
        if line.startswith(refresh_ci_locks.EXCEPTION_PREFIX)
    ]


@pytest.mark.parametrize("filename", ALL_LOCKS)
def test_a_lock_records_exactly_the_cooldown_exceptions_of_its_table_row(
    filename: str,
) -> None:
    lock = refresh_ci_locks.lock_by_filename(filename)
    assert _recorded_exception_lines(filename) == lock.exception_lines, (
        f"scripts/ci/{filename} and scripts/dev/ci_lock_table.py disagree about the "
        f"cooldown exceptions; run `python {REFRESH}`"
    )


@pytest.mark.parametrize("filename", ALL_LOCKS)
def test_a_cooldown_exception_names_a_package_the_lock_pins(filename: str) -> None:
    lock = refresh_ci_locks.lock_by_filename(filename)
    pinned = {pin.name for pin in load_pins(filename)}
    for name, _until in lock.cooldown_exceptions:
        assert canonicalize_name(name) in pinned, (
            f"scripts/ci/{filename} has a cooldown exception for {name}, which the "
            "lock does not pin"
        )


@pytest.mark.parametrize("filename", ALL_LOCKS)
def test_no_cooldown_exception_has_lapsed_or_postdates_its_lock(
    filename: str,
) -> None:
    lock = refresh_ci_locks.lock_by_filename(filename)
    header = refresh_ci_locks.parse_header(_read_text(filename))
    assert header.cutoff is not None
    assert header.locked_as_of is not None
    stale = lock.stale_exceptions(header.cutoff)
    assert not stale, (
        f"the cutoff {header.cutoff} of scripts/ci/{filename} already reaches the "
        f"cooldown exception for {', '.join(stale)}: the cooldown has caught up, so "
        f"remove the entry from scripts/dev/ci_lock_table.py and run `python {REFRESH}`"
    )
    for name, until in lock.cooldown_exceptions:
        assert until[:10] <= header.locked_as_of[:10], (
            f"the cooldown exception for {name} ends at {until}, after the lock date "
            f"{header.locked_as_of} of scripts/ci/{filename}"
        )


def test_locks_share_one_lock_date_and_one_cutoff() -> None:
    headers = {
        filename: refresh_ci_locks.parse_header(_read_text(filename))
        for filename in ALL_LOCKS
    }
    dates = {name: header.locked_as_of for name, header in headers.items()}
    cutoffs = {name: header.cutoff for name, header in headers.items()}
    cooldowns = {name: header.cooldown_days for name, header in headers.items()}
    assert len(set(dates.values())) == 1, (
        f"the locks were compiled on different dates: {dates}; "
        f"run `python {REFRESH}` so they move together"
    )
    assert len(set(cutoffs.values())) == 1, (
        f"the locks were compiled with different cutoffs: {cutoffs}; "
        f"run `python {REFRESH}` so they move together"
    )
    assert len(set(cooldowns.values())) == 1, cooldowns


def test_table_matches_the_files_on_disk() -> None:
    table = {lock.filename for lock in refresh_ci_locks.LOCKS}
    on_disk = {path.name for path in CI_DIR.glob("requirements-ci-*.txt")} - {PIP_LOCK}
    assert table == on_disk


